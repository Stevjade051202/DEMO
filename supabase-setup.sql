-- Run this in Supabase -> SQL Editor (Steps 2 and 11 of the lesson)

create table if not exists public.students (
  id bigint generated by default as identity primary key,
  name text not null,
  course text not null
);

insert into public.students (name, course)
select sample.name, sample.course
from (values
  ('Alex Santos', 'BSIT'),
  ('Jamie Cruz', 'BSCS'),
  ('Taylor Reyes', 'BSIT')
) as sample(name, course)
where not exists (
  select 1
  from public.students as existing
  where existing.name = sample.name
    and existing.course = sample.course
);

-- Security: Row Level Security + only the actions the demo needs
alter table public.students enable row level security;

drop policy if exists "Anyone can read students (demo)" on public.students;
create policy "Anyone can read students (demo)"
  on public.students for select
  to anon
  using (true);

drop policy if exists "Anyone can add students (demo)" on public.students;
create policy "Anyone can add students (demo)"
  on public.students for insert
  to anon
  with check (true);

-- Demo only: anyone using the app can delete any student record.
drop policy if exists "Anyone can delete students (demo)" on public.students;
create policy "Anyone can delete students (demo)"
  on public.students for delete
  to anon
  using (true);

-- Remove the insert and delete policies after class to block public writes.
